-- Crear la base de datos.
CREATE DATABASE bd_laboratorio_orm
    WITH ENCODING 'UTF8'
    TEMPLATE template0;


-- Conectarse a bd_laboratorio_orm antes de continuar.

-- Crear el esquema del laboratorio.
CREATE SCHEMA IF NOT EXISTS laboratorio;


-- Tabla para los tipos de equipo.
CREATE TABLE IF NOT EXISTS laboratorio.tipo_equipo (
    id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(250)
);


-- Tabla para los equipos.
CREATE TABLE IF NOT EXISTS laboratorio.equipo (
    id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL,
    marca VARCHAR(100),
    estado VARCHAR(30) NOT NULL,
    cantidad INTEGER NOT NULL,
    id_tipo BIGINT NOT NULL,

    CONSTRAINT chk_cantidad
        CHECK (cantidad >= 0),

    CONSTRAINT chk_estado
        CHECK (estado IN (
            'Disponible',
            'En mantenimiento',
            'Fuera de servicio'
        )),

    CONSTRAINT fk_equipo_tipo
        FOREIGN KEY (id_tipo)
        REFERENCES laboratorio.tipo_equipo(id_tipo)
);


