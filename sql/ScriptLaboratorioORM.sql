-- Mostrar los equipos con su tipo correspondiente.
SELECT
    e.id_equipo,
    e.codigo,
    e.nombre,
    e.marca,
    e.estado,
    e.cantidad,
    t.nombre AS tipo
FROM laboratorio.equipo e
INNER JOIN laboratorio.tipo_equipo t
    ON e.id_tipo = t.id_tipo
ORDER BY e.id_equipo;
